export const blankPlannedExtra=():PlannedExtraDraft=>({key:crypto.randomUUID(),description:'',quantity:'1',unit:'cái',unit_price:''});
const scaled=(value:string,digits:number)=>{
 if(!new RegExp(`^\\d{1,24}(?:\\.\\d{1,${digits}})?$`).test(value))return null;
 const[whole,fraction='']=value.split('.');return BigInt(whole)*10n**BigInt(digits)+BigInt(fraction.padEnd(digits,'0'));
};
const exactAmount=(value:bigint)=>`${value/10000n}.${String(value%10000n).padStart(4,'0')}`;
/** Preview only; the persisted authoritative total is generated by PostgreSQL numeric. */
export function plannedExtraPreview(quantity:string,price:string){
 const q=scaled(quantity,2),p=scaled(price,2);return q===null||p===null?null:exactAmount(q*p);
}
export function sumPlannedExtraAmounts(values:Array<string|null|undefined>){return exactAmount(values.reduce<bigint>((sum,value)=>sum+(value?scaled(value,4)||0n:0n),0n));}
export function formatPlannedExtraAmount(value:string|null|undefined){
 if(value==null)return 'Ẩn chi phí';if(!/^\d+(?:\.\d{1,4})?$/.test(value))return '—';
 const[whole,fraction='']=value.split('.'),tail=fraction.replace(/0+$/,'');return`${whole.replace(/\B(?=(\d{3})+(?!\d))/g,'.')}${tail?','+tail:''} ₫`;
}
export const plannedExtraPayload=(rows:PlannedExtraDraft[])=>rows.map(({description,quantity,unit,unit_price})=>({description,quantity,unit,unit_price}));
export function plannedExtraDraftError(rows:PlannedExtraDraft[]){
 if(rows.length>50)return 'Mỗi sản phẩm có tối đa 50 dòng cộng thêm đang dùng.';
 for(const row of rows){
  if(!row.description.trim()||row.description.trim().length>200)return 'Nhập nội dung cộng thêm từ 1 đến 200 ký tự.';
  if(!/^\d{1,10}(?:\.\d{1,2})?$/.test(row.quantity)||scaled(row.quantity,2)===0n)return 'Số lượng cộng thêm phải lớn hơn 0, tối đa 2 chữ số thập phân.';
  if(!/^\d{1,14}(?:\.\d{1,2})?$/.test(row.unit_price))return 'Đơn giá cộng thêm phải không âm, tối đa 2 chữ số thập phân.';
  const amount=plannedExtraPreview(row.quantity,row.unit_price);
  if(amount&&scaled(amount,4)!>999999999999999999n)return 'Thành tiền cộng thêm vượt giới hạn ghi nhận tiền công.';
 }
 return '';
}
