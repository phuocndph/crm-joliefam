#!/bin/sh
# Deliberately restores only to a NEW isolated database and NEW local assets directory.
set -eu
umask 077
backup_dir="${1:?Usage: restore-isolated.sh ABSOLUTE_BACKUP_DIR isolated_NAME ABSOLUTE_NEW_ASSET_DIR}"
restore_db="${2:?Missing new isolated database name}"
restore_assets="${3:?Missing new asset directory}"
case "$backup_dir" in /*) ;; *) echo "Backup path must be absolute" >&2; exit 2;; esac
case "$restore_assets" in /*) ;; *) echo "Asset path must be absolute" >&2; exit 2;; esac
case "$restore_assets" in /|/app|/srv|/var|/root|/home|*/..|*/../*) echo "Use a dedicated new asset directory" >&2; exit 2;; esac
case "$restore_db" in isolated_*) ;; *) echo "Database must start with isolated_" >&2; exit 2;; esac
case "$restore_db" in *[!a-zA-Z0-9_]*) echo "Invalid database name" >&2; exit 2;; esac
[ "${#restore_db}" -le 63 ] || exit 2
[ ! -e "$restore_assets" ] || { echo "Asset destination already exists; refusing overwrite" >&2; exit 2; }
(cd "$backup_dir" && sha256sum -c SHA256SUMS)
tar -tzf "$backup_dir/assets.tar.gz" | awk '/^\// || /(^|\/)\.\.(\/|$)/ {bad=1} END {exit bad}' || { echo "Unsafe archive paths" >&2; exit 2; }
# Symlinks/hardlinks could redirect extraction outside the destination.
tar -tvzf "$backup_dir/assets.tar.gz" | awk 'substr($0,1,1) ~ /[lh]/ {bad=1} END {exit bad}' || { echo "Linked assets unsupported in restore" >&2; exit 2; }
ENV_FILE="${DEPLOY_ENV_FILE:-deploy/.env.production}"
compose() { docker compose --env-file "$ENV_FILE" -f deploy/compose.yml "$@"; }
# createdb fails for an existing DB. No drop, clean or overwrite flag is ever used.
compose exec -T postgres sh -c 'createdb -U "$POSTGRES_USER" -O "$APP_DATABASE_USER" "$1"' sh "$restore_db"
compose exec -T postgres sh -c 'pg_restore -U "$POSTGRES_USER" --role "$APP_DATABASE_USER" -d "$1" --exit-on-error --no-owner --no-acl' sh "$restore_db" < "$backup_dir/database.dump"
mkdir -m 700 "$restore_assets"
# Archive is generated by our backup script from the assets volume; verify provenance first.
tar -xzf "$backup_dir/assets.tar.gz" -C "$restore_assets"
printf 'Restore complete in isolated database %s and assets %s. Live database unchanged.\n' "$restore_db" "$restore_assets"

